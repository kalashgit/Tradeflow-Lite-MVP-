'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const app=fs.readFileSync('public/app.js','utf8');
const html=fs.readFileSync('public/index.html','utf8');
const sw=fs.readFileSync('public/sw.js','utf8');
const css=fs.readFileSync('public/opportunity-dossier.css','utf8');
const source=fs.readFileSync('public/opportunity-dossier.js','utf8');
const scope={window:{TradeFlowEngine:require('../public/tradeflow-engine.js')},URL,console};
vm.runInNewContext(source,scope,{timeout:3000});
const ux=scope.window.TradeFlowDossier;
assert.ok(ux&&ux.dossier&&ux.workflow,'Two independent drilldown screens');
const record={id:'a-1',project_name:'Campus retrofit',address:'6801 River Place Blvd, Austin, TX 78726, Texas',opportunity_type:'potential_opportunity',evidence_status:'source_supported',source_url:'https://example.org/source',source_date:'2026-09-30',latitude:30.2,longitude:-97.7,contact_person:'Facilities'};
const dossier=ux.dossier(record);
assert.ok(dossier.includes('Opportunity dossier')&&dossier.includes('6801 River Place'),'Address displayed');
assert.ok(dossier.includes('Key details')&&dossier.includes('Evidence &amp; source'),'Reference card structure');
assert.ok(dossier.includes('Open original source')&&dossier.includes('View location on map')&&dossier.includes('Contact &amp; workflow'),'Actions exist');
assert.ok(dossier.includes('Not an open subcontract'),'Demand must not be invented');
assert.ok(dossier.includes('tf-od-photo-fallback'),'No fake building photo');
assert.ok(!dossier.includes('<img src='),'Only supplied photos');
const withPhoto=ux.dossier({...record,photo_url:'https://photos.example.org/building.jpg'});
assert.ok(withPhoto.includes('aspect')===false&&withPhoto.includes('photos.example.org/building.jpg'),'Licensed source photo slot');
assert.ok(ux.dossier({...record,photo_url:'javascript:alert(1)'}).includes('tf-od-photo-fallback'),'Reject unsafe photo schemes');
const wf=ux.workflow(record,{settings:[{id:'growth-profiles-v1',icps:[{id:'electrical',name:'Electrical contractors'}]}]});
for(const label of ['Contact &amp; workflow','Pipeline stage','Next follow-up','Notes / next steps','Contact person / department','Phone','Email','Ideal customer profile','Save contact &amp; workflow'])assert.ok(wf.includes(label),'Field: '+label);
assert.ok(wf.includes('Electrical contractors')&&wf.includes('data-calendar-action="opportunity"'),'ICP and calendar integration');
assert.ok(app.includes("if(detail&&window.TradeFlowDossier)return"),'Only tapped record invokes new screen');
assert.ok(app.includes("opportunityDetailScreen='workflow'"),'Navigation opens workflow');
assert.ok(app.includes('tfOdContactWorkflowForm'),'Local save hook');
assert.ok(app.includes("await put('opportunities',record)"),'Existing local store');
assert.ok(app.includes('data-op-ux="import"')&&app.includes('data-op-ux="export"')&&app.includes('data-action="opportunityMapAll"'),'Main page remains');
assert.ok(css.includes('aspect-ratio:4/3')&&css.includes('.tf-od-hero-layout'),'Correct reference photo ratio');
assert.ok(html.includes('./opportunity-dossier.js')&&html.includes('./opportunity-dossier.css'));
assert.ok(sw.includes('./opportunity-dossier.js')&&sw.includes('./opportunity-dossier.css'),'Offline resources present');
console.log('PASS: Two-stage Opportunity dossier and workflow, safe source photos, reference layout, local saves, unchanged Opportunity dashboard');
